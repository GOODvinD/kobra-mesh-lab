#!/usr/bin/env python3
"""Create a self-contained JavaScript data-URL asset from the user's exact SVG.
Base silhouette and printed artwork stay separate so probe data remains legible.
"""
from pathlib import Path
import base64,copy,json,re
from lxml import etree
ROOT=Path(__file__).resolve().parent
SOURCE=ROOT/'assets/pei-kobra-x.svg'
OUT=ROOT/'plate-assets.js'
NS='{http://www.w3.org/2000/svg}'

def build():
    data=SOURCE.read_bytes()
    # Reject active/external content; this intentionally remains a static local asset.
    tree=etree.fromstring(data)
    assert tree.tag==NS+'svg'
    for node in tree.iter():
        local=etree.QName(node.tag).localname
        assert local not in ('script','foreignObject','image','animate','set','animateMotion','animateTransform'), f'Unsupported SVG element {local}'
        for key,val in node.attrib.items():
            attr=etree.QName(key).localname.lower()
            assert not attr.startswith('on'), 'Inline event handler forbidden'
            if attr in ('href','src'):
                assert val.startswith('#'), f'External resource not permitted: {val}'
            if attr=='style':
                assert 'url(' not in val.lower(), 'External style resource forbidden'
    def clone(): return copy.deepcopy(tree)
    base=clone(); marks=clone()
    for node in list(base):
        if etree.QName(node.tag).localname=='g' and node.get('id')!='plate': base.remove(node)
    body=base.xpath('.//*[@id="plate"]')[0]
    perimeter=body.xpath('.//*[@id="white-perimeter"]')[0]
    body.remove(perimeter)
    # Markings group receives the identical perimeter as the source file.
    for node in list(marks):
        if etree.QName(node.tag).localname=='g' and node.get('id')=='plate': marks.remove(node)
    marks.append(perimeter)
    def url(x):return 'data:image/svg+xml;base64,'+base64.b64encode(etree.tostring(x,encoding='UTF-8',xml_declaration=True)).decode('ascii')
    baseurl, marksurl = url(base), url(marks)
    # Bounds of the main square excluding the front/right orientation tab. 0,0 is lower left.
    js='''/* Generated by prepare_plate_asset.py from assets/pei-kobra-x.svg. Never fetches a URL. */\n'use strict';\nconst KOBRA_PLATE = (() => {\n  const svgBounds={left:81.2,right:1172.3,top:67.3,bottom:1155.2,width:1254,height:1254};\n  const size=265;\n  const dx=svgBounds.right-svgBounds.left,dy=svgBounds.bottom-svgBounds.top;\n  const worldRect=[-svgBounds.left/dx*size,(svgBounds.bottom-svgBounds.height)/dy*size,\n     (svgBounds.width-svgBounds.left)/dx*size,svgBounds.bottom/dy*size];\n  const images={};let complete=0;\n  const source={base:__BASE__,marks:__MARKS__};\n  for(const key of ['base','marks']){\n    const img=new Image();images[key]=img;\n    img.onload=()=>{complete++;if(complete===2)window.dispatchEvent(new Event('kobra-plate-ready'));};\n    img.onerror=()=>console.warn('Could not render the embedded PEI plate layer:',key);\n    img.src=source[key];\n  }\n  return {images,worldRect,size,svgBounds,isReady:(key)=>images[key]?.complete&&images[key]?.naturalWidth>0};\n})();\n'''
    js=js.replace('__BASE__',json.dumps(baseurl)).replace('__MARKS__',json.dumps(marksurl))
    OUT.write_text(js,encoding='utf-8')
    print(f'Generated {OUT.name} from {SOURCE.name} ({len(data)} original SVG bytes)')
if __name__=='__main__':build()
